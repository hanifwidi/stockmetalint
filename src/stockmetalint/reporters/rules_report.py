"""Renderers for ``stockmetalint rules list/show`` (text, JSON, Markdown)."""

from __future__ import annotations

from typing import Any

from stockmetalint.reporters.json_report import dumps
from stockmetalint.rules.registry import Rule, RuleRegistry


def registry_dict(registry: RuleRegistry) -> dict[str, Any]:
    return {
        "platform": registry.platform,
        "rule_profile_version": registry.profile_id,
        "verification_summary": registry.verification_summary,
        "template_header": list(registry.template_header),
        "rules": [rule.to_dict() for rule in registry.rules.values()],
    }


def render_list_text(registry: RuleRegistry) -> str:
    rules = list(registry.rules.values())
    width = max(len(r.rule_id) for r in rules)
    lines = [f"{registry.profile_id}: {len(rules)} rules ({registry.verification_label})", ""]
    lines.append(f"{'RULE'.ljust(width)}  SEVERITY  SCOPE           VERIFICATION            TITLE")
    lines.extend(
        f"{r.rule_id.ljust(width)}  {r.severity.value:<8}  {r.scope:<14}  "
        f"{r.verification:<22}  {r.title}"
        + ("  [editorial profile only]" if r.profiles == ("editorial",) else "")
        for r in rules
    )
    lines += ["", registry.verification_summary]
    return "\n".join(lines) + "\n"


def render_rule_text(rule: Rule) -> str:
    fields = [
        ("Rule", rule.rule_id),
        ("Title", rule.title),
        ("Severity", rule.severity.value),
        ("Scope", rule.scope),
        ("Profiles", ", ".join(rule.profiles)),
        ("Limit", "-" if rule.limit is None else str(rule.limit)),
        ("Description", rule.description),
        ("Notes", rule.notes or "-"),
        ("Source", rule.source_url),
        ("Source updated", rule.source_updated or "unknown"),
        ("Verification", rule.verification),
        ("Verified at", rule.verified_at or "not verified"),
        ("Fix rule", rule.fix_rule or "-"),
    ]
    width = max(len(k) for k, _ in fields)
    return "\n".join(f"{k.ljust(width)}  {v}" for k, v in fields) + "\n"


def render_list_json(registry: RuleRegistry) -> str:
    return dumps(registry_dict(registry))


def render_rule_json(rule: Rule) -> str:
    return dumps(rule.to_dict())


def _md(text: str) -> str:
    return text.replace("|", "\\|")


def render_list_markdown(registry: RuleRegistry) -> str:
    """Markdown catalog used to generate docs/rules.md."""
    lines = [
        "# Rule catalog",
        "",
        (
            "<!-- Generated by `stockmetalint rules list --format markdown`. "
            "Do not edit by hand; a test fails if this file is stale. -->"
        ),
        "",
        f"Rule profile: `{registry.profile_id}` (platform `{registry.platform}`).",
        "",
        f"> {registry.verification_summary}",
        "",
        (
            "Verification vocabulary: `verified` (read on the live official page), "
            "`snippet-corroborated` (search-index snippets quoting the official page), "
            "`summary-corroborated` (search summary only), `partially-corroborated`, "
            "`seed-unverified` (from the project brief), `standard-reference` (public standard), "
            "`tool-defined` (StockMetaLint's own rule, not an Adobe policy)."
        ),
        "",
        "| Rule | Severity | Scope | Verification | Limit | Title |",
        "|---|---|---|---|---|---|",
    ]
    for r in registry.rules.values():
        limit = "" if r.limit is None else f"`{r.limit}`"
        lines.append(
            f"| [{r.rule_id}](#{r.rule_id.lower()}) | {r.severity.value} | {r.scope} | "
            f"{r.verification} | {limit} | {_md(r.title)} |"
        )
    for r in registry.rules.values():
        lines += [
            "",
            f"## {r.rule_id}",
            "",
            (
                f"**{_md(r.title)}** — severity `{r.severity.value}`, scope `{r.scope}`, "
                f"profiles {', '.join(f'`{p}`' for p in r.profiles)}."
            ),
            "",
            r.description,
            "",
            f"- Limit: {'—' if r.limit is None else f'`{r.limit}`'}",
            f"- Source: <{r.source_url}> (updated: {r.source_updated or 'unknown'})",
            f"- Verification: `{r.verification}`; verified at: {r.verified_at or 'not verified'}",
            f"- Fix rule: {f'`{r.fix_rule}`' if r.fix_rule else '—'}",
        ]
        if r.notes:
            lines.append(f"- Notes: {r.notes}")
    return "\n".join(lines) + "\n"
